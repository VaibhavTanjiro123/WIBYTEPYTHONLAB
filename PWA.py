import turtle

t = turtle.Turtle()

t.shape('classic')
t.pencolor('HotPink')
t.fillcolor('PeachPuff')
t.penup()
t.speed(1)
t.goto(-100,100)
t.pendown()
t.pensize(4)
t.begin_fill()
t.goto(100,100)
t.goto(100,-100)
t.goto(-100,-100)
t.goto(-100,100)
t.end_fill()
t.penup()
t.goto(0,30)
t.pendown()
t.setheading(90)
t.pencolor('YellowGreen')
t.fillcolor('GhostWhite')
t.begin_fill()
t.circle(25)
t.circle(-25)
t.end_fill()
t.penup()
t.goto(-15, 30)
t.dot(20)
t.goto(15, 30)
t.dot(20)
t.goto(35, -20)
t.pencolor('AliceBlue')
t.pensize(8)
t.pendown()
t.setheading(-90)
t.circle(-35, 180)
turtle.mainloop()